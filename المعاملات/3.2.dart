void main() {
  int a = 15;
  int b = 20;

  // إجراء المقارنات وطباعة النتيجة (صواب أم خطأ)
  print("هل a أكبر من b؟ ${a > b}");       // النتيجة: false
  print("هل a أصغر من b؟ ${a < b}");       // النتيجة: true
  print("هل a يساوي b؟ ${a == b}");         // النتيجة: false
  print("هل a لا يساوي b؟ ${a != b}");      // النتيجة: true
}