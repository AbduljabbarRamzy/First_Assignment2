void main() {
  List<int>? numbers; // قائمة قيمتها الحالية null
  
  // نستخدم المعامل (?.) قبل استدعاء الدالة
  // هذا يعني: نفذ دالة الترتيب sort() فقط إذا كانت القائمة لا تساوي null
  numbers?.sort(); 
  
  print(numbers); // النتيجة ستكون null، ولن ينهار البرنامج (Crash) بسبب محاولة ترتيب قائمة فارغة
}